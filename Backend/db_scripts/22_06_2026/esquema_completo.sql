/* ============================================================================
   1) USUARIOS Y CONTROL DE ACCESO
   ============================================================================ */

CREATE TABLE TIPOUSUARIO (
    IDTIPOUSUARIO   NVARCHAR(50)    NOT NULL PRIMARY KEY,
    DESCRIPCION     NVARCHAR(255)   NOT NULL
);
GO

CREATE TABLE USUARIO (
    IDUSUARIO           NVARCHAR(50)    NOT NULL PRIMARY KEY,
    CONTRA              NVARCHAR(255)   NOT NULL,   -- guardar HASH, no texto plano
    NOMBRE              NVARCHAR(100)   NOT NULL,
    APELLIDO            NVARCHAR(100)   NOT NULL,
    DNI                 NVARCHAR(20)    NOT NULL UNIQUE,
    FECHANACIMIENTO     CHAR(8)         NULL CHECK (FECHANACIMIENTO LIKE '[0-3][0-9][0-1][0-9][0-9][0-9][0-9][0-9]'),
    DIRECCION           NVARCHAR(255)   NULL,
    ESTADO              NVARCHAR(50)    NOT NULL DEFAULT 'Activo',
    DISTRITO            NVARCHAR(100)   NULL,
    COLEGIO             NVARCHAR(150)   NULL,
    GRADO               NVARCHAR(50)    NULL,
    FECHAACTIVO         CHAR(8)         NULL CHECK (FECHAACTIVO LIKE '[0-3][0-9][0-1][0-9][0-9][0-9][0-9][0-9]'),
    EMAIL               NVARCHAR(150)   NOT NULL UNIQUE,
    TELPERSONAL         NVARCHAR(20)    NULL,
    TELAPODERADO        NVARCHAR(20)    NULL,
    SITUACIONACADEMICA  NVARCHAR(100)   NULL,
    IDTIPOUSUARIO       NVARCHAR(50)    NOT NULL
        FOREIGN KEY REFERENCES TIPOUSUARIO(IDTIPOUSUARIO)
);
GO
CREATE INDEX IX_USUARIO_TIPO ON USUARIO(IDTIPOUSUARIO);
GO

CREATE TABLE MODULO (
    IDMODULO            NVARCHAR(50)    NOT NULL PRIMARY KEY,
    NOMBRE              NVARCHAR(100)   NOT NULL,
    DESCRIPCION         NVARCHAR(255)   NULL,
    ICONO               NVARCHAR(100)   NULL,
    ORDEN               INT             NULL,
    ACTIVO              BIT             NOT NULL DEFAULT 1,
    FECHACREACION       CHAR(8)         NULL CHECK (FECHACREACION LIKE '[0-3][0-9][0-1][0-9][0-9][0-9][0-9][0-9]'),
    FECHAACTUALIZACION  CHAR(8)         NULL CHECK (FECHAACTUALIZACION LIKE '[0-3][0-9][0-1][0-9][0-9][0-9][0-9][0-9]')
);
GO

CREATE TABLE SUBMODULO (
    IDSUBMODULO     NVARCHAR(50)    NOT NULL PRIMARY KEY,
    NOMBRE          NVARCHAR(100)   NOT NULL,
    DESCRIPCION     NVARCHAR(255)   NULL,
    ICONO           NVARCHAR(100)   NULL,
    ORDEN           INT             NULL,
    ACTIVO          BIT             NOT NULL DEFAULT 1,
    IDMODULO        NVARCHAR(50)    NOT NULL
        FOREIGN KEY REFERENCES MODULO(IDMODULO)
);
GO
CREATE INDEX IX_SUBMODULO_MODULO ON SUBMODULO(IDMODULO);
GO

CREATE TABLE TIPO_PERMISO (
    IDTIPOPERMISO   NVARCHAR(50)    NOT NULL PRIMARY KEY,
    DESCRIPCION     NVARCHAR(255)   NOT NULL    -- ej. VER, CREAR, EDITAR, ELIMINAR
);
GO

-- Permisos por ROL (tipo de usuario) sobre un módulo
CREATE TABLE GRUPO_MODULO (
    IDGRUPOMODULO   NVARCHAR(50)    NOT NULL PRIMARY KEY,
    IDTIPOUSUARIO   NVARCHAR(50)    NOT NULL FOREIGN KEY REFERENCES TIPOUSUARIO(IDTIPOUSUARIO),
    IDMODULO        NVARCHAR(50)    NOT NULL FOREIGN KEY REFERENCES MODULO(IDMODULO),
    IDTIPOPERMISO   NVARCHAR(50)    NOT NULL FOREIGN KEY REFERENCES TIPO_PERMISO(IDTIPOPERMISO),
    CONSTRAINT UQ_GRUPO_MODULO UNIQUE (IDTIPOUSUARIO, IDMODULO, IDTIPOPERMISO)
);
GO

-- Permisos específicos por USUARIO sobre un módulo (excepciones)
CREATE TABLE USUARIO_MODULO (
    IDUSUARIOMODULO NVARCHAR(50)    NOT NULL PRIMARY KEY,
    IDUSUARIO       NVARCHAR(50)    NOT NULL FOREIGN KEY REFERENCES USUARIO(IDUSUARIO),
    IDMODULO        NVARCHAR(50)    NOT NULL FOREIGN KEY REFERENCES MODULO(IDMODULO),
    IDTIPOPERMISO   NVARCHAR(50)    NOT NULL FOREIGN KEY REFERENCES TIPO_PERMISO(IDTIPOPERMISO),
    CONSTRAINT UQ_USUARIO_MODULO UNIQUE (IDUSUARIO, IDMODULO, IDTIPOPERMISO)
);
GO

/* ============================================================================
   2) MATERIAS, EXÁMENES Y PREGUNTAS
