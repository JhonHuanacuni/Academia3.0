    FECHACREACION CHAR(8)       NULL CHECK (FECHACREACION LIKE '[0-3][0-9][0-1][0-9][0-9][0-9][0-9][0-9]'),
    HORACREACION  CHAR(8)       NULL CHECK (HORACREACION  LIKE '[0-2][0-9]:[0-5][0-9]:[0-5][0-9]'),
