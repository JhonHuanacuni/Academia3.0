CREATE TABLE MATERIA (
    IDMATERIA   NVARCHAR(50)    NOT NULL PRIMARY KEY,
    CODIGO      NVARCHAR(50)    NULL,
    NOMBRE      NVARCHAR(150)   NOT NULL
);
GO

CREATE TABLE EXAMEN (
    IDEXAMEN        NVARCHAR(50)    NOT NULL PRIMARY KEY,
    TITULO          NVARCHAR(200)   NOT NULL,
    DESCRIPCION     NVARCHAR(MAX)   NULL,
    TIPO            INT             NULL,   -- catálogo de tipos de examen (1,2,3...)
    DURACIONMIN     INT             NULL,
    PUNTAJETOTAL    DECIMAL(6,2)    NULL,
    PUNTAJEAPROBADO DECIMAL(6,2)    NULL,
    FECHAINICIO     CHAR(8)         NULL CHECK (FECHAINICIO LIKE '[0-3][0-9][0-1][0-9][0-9][0-9][0-9][0-9]'),
    FECHAFIN        CHAR(8)         NULL CHECK (FECHAFIN    LIKE '[0-3][0-9][0-1][0-9][0-9][0-9][0-9][0-9]'),
    HORAINICIO      CHAR(8)         NULL CHECK (HORAINICIO  LIKE '[0-2][0-9]:[0-5][0-9]:[0-5][0-9]'),
    HORAFIN         CHAR(8)         NULL CHECK (HORAFIN     LIKE '[0-2][0-9]:[0-5][0-9]:[0-5][0-9]'),
    TIEMPOLIMITE    CHAR(8)         NULL CHECK (TIEMPOLIMITE LIKE '[0-2][0-9]:[0-5][0-9]:[0-5][0-9]'),
    INTENTOSMAX     INT             NULL DEFAULT 1,
    VISIBLE         BIT             NOT NULL DEFAULT 1,
    IDUSUARIO       NVARCHAR(50)    NOT NULL
        FOREIGN KEY REFERENCES USUARIO(IDUSUARIO)   -- docente que lo crea
);
GO
CREATE INDEX IX_EXAMEN_USUARIO ON EXAMEN(IDUSUARIO);
GO

CREATE TABLE PREGUNTA (
    IDPREGUNTA      NVARCHAR(50)    NOT NULL PRIMARY KEY,
    TITULO          NVARCHAR(255)   NOT NULL,
    DESCRIPCION     NVARCHAR(MAX)   NULL,
    PUNTAJE         DECIMAL(6,2)    NULL,
    ORDEN           INT             NULL,
    IMAGEURL        NVARCHAR(255)   NULL,
    IDEXAMEN        NVARCHAR(50)    NOT NULL FOREIGN KEY REFERENCES EXAMEN(IDEXAMEN),
    IDMATERIA       NVARCHAR(50)    NULL     FOREIGN KEY REFERENCES MATERIA(IDMATERIA)
);
GO
CREATE INDEX IX_PREGUNTA_EXAMEN  ON PREGUNTA(IDEXAMEN);
CREATE INDEX IX_PREGUNTA_MATERIA ON PREGUNTA(IDMATERIA);
GO

CREATE TABLE ALTERNATIVA (
    IDALTERNATIVA   NVARCHAR(50)    NOT NULL PRIMARY KEY,
    DESCRIPCION     NVARCHAR(MAX)   NOT NULL,
    ESCORRECTA      BIT             NOT NULL DEFAULT 0,
    ORDEN           INT             NULL,
    IMAGEURL        NVARCHAR(255)   NULL,
    IDPREGUNTA      NVARCHAR(50)    NOT NULL FOREIGN KEY REFERENCES PREGUNTA(IDPREGUNTA)
);
GO
CREATE INDEX IX_ALTERNATIVA_PREGUNTA ON ALTERNATIVA(IDPREGUNTA);
GO

CREATE TABLE INTENTO_EXAMEN (
    IDINTENTOEXAMEN NVARCHAR(50)    NOT NULL PRIMARY KEY,
    NUMEROINTENTO   INT             NOT NULL DEFAULT 1,
    FECHAINICIO     CHAR(8)         NULL CHECK (FECHAINICIO LIKE '[0-3][0-9][0-1][0-9][0-9][0-9][0-9][0-9]'),
    HORAINICIO      CHAR(8)         NULL CHECK (HORAINICIO  LIKE '[0-2][0-9]:[0-5][0-9]:[0-5][0-9]'),
    FECHAFIN        CHAR(8)         NULL CHECK (FECHAFIN    LIKE '[0-3][0-9][0-1][0-9][0-9][0-9][0-9][0-9]'),
    HORAFIN         CHAR(8)         NULL CHECK (HORAFIN     LIKE '[0-2][0-9]:[0-5][0-9]:[0-5][0-9]'),
    PUNTAJEOBTENIDO DECIMAL(6,2)    NULL,
    CANTCORRECTAS   INT             NULL DEFAULT 0,
    CANTINCORRECTAS INT             NULL DEFAULT 0,
    CANTSINRESPONDER INT            NULL DEFAULT 0,
    ESTADO          INT             NULL,       -- ej. 0=en curso, 1=finalizado
    APROBADO        BIT             NULL,
    IDEXAMEN        NVARCHAR(50)    NOT NULL FOREIGN KEY REFERENCES EXAMEN(IDEXAMEN),
    IDUSUARIO       NVARCHAR(50)    NOT NULL FOREIGN KEY REFERENCES USUARIO(IDUSUARIO)
);
GO
CREATE INDEX IX_INTENTO_EXAMEN_EXAMEN  ON INTENTO_EXAMEN(IDEXAMEN);
CREATE INDEX IX_INTENTO_EXAMEN_USUARIO ON INTENTO_EXAMEN(IDUSUARIO);
GO

CREATE TABLE RESPUESTA_ALUMNO (
    IDRESPUESTAALUMNO NVARCHAR(50)  NOT NULL PRIMARY KEY,
    PUNTAJEOBTENIDO   DECIMAL(6,2)  NULL,
    RESPABIERTA       NVARCHAR(MAX) NULL,       -- para preguntas abiertas
    IDINTENTOEXAMEN   NVARCHAR(50)  NOT NULL FOREIGN KEY REFERENCES INTENTO_EXAMEN(IDINTENTOEXAMEN),
    IDPREGUNTA        NVARCHAR(50)  NOT NULL FOREIGN KEY REFERENCES PREGUNTA(IDPREGUNTA),
    IDALTERNATIVA     NVARCHAR(50)  NULL     FOREIGN KEY REFERENCES ALTERNATIVA(IDALTERNATIVA)
);
GO
CREATE INDEX IX_RESP_ALUMNO_INTENTO ON RESPUESTA_ALUMNO(IDINTENTOEXAMEN);
CREATE INDEX IX_RESP_ALUMNO_PREGUNTA ON RESPUESTA_ALUMNO(IDPREGUNTA);
GO

